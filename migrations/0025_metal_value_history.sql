-- Historical monthly gold/silver portfolio value, backfilled from the "La
-- Lana" spreadsheet's Raw Monthly sheet (Ag Oz / Silver Value / Au Oz / Gold
-- Value columns, Jan 2023 - Jun 2026). This feeds getMetalValueHistory's
-- "value over time" chart on the precious metals dashboard, but deliberately
-- lives in its own table rather than account_balance_history: the existing
-- "Historical Hard Assets (La Lana)" account already carries a blended
-- (metals + other hard assets) balance for this same date range and drives
-- the net-worth-by-category chart, so writing these more granular per-metal
-- numbers into account_balance_history for the same accounts/dates would
-- double-count precious metals in net worth. This table is read-only
-- history and never touches net worth.
CREATE TABLE metal_value_history (
  id TEXT PRIMARY KEY,
  metal TEXT NOT NULL, -- gold | silver
  date TEXT NOT NULL, -- ISO date, typically a month-end snapshot
  value_usd REAL NOT NULL,
  troy_oz REAL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (metal, date)
);

